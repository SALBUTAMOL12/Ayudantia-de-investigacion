#!/usr/bin/env python3
"""Copy results (tables, figures, paper_numbers.tex) into the Overleaf clone and compile."""
import os, shutil, subprocess, glob
from scripts.directories import PROJECT_ROOT, results_tables, results_figures, paper_numbers

OV = os.path.join(PROJECT_ROOT, 'overleaf')
os.makedirs(os.path.join(OV, 'tables'), exist_ok=True); os.makedirs(os.path.join(OV, 'figures'), exist_ok=True)
for f in glob.glob(os.path.join(results_tables, '*.tex')):
    shutil.copy(f, os.path.join(OV, 'tables', os.path.basename(f)))
for f in glob.glob(os.path.join(results_figures, '*.png')) + glob.glob(os.path.join(results_figures, '*.pdf')):
    shutil.copy(f, os.path.join(OV, 'figures', os.path.basename(f)))
if os.path.exists(paper_numbers):
    shutil.copy(paper_numbers, os.path.join(OV, 'paper_numbers.tex'))
else:
    open(os.path.join(OV, 'paper_numbers.tex'), 'w').write('% generated by the pipeline\n')
# placeholders for tables not yet produced
for t in ['poverty_by_ethnicity_2024', 'poverty_by_ethnicity_1992', 'poverty_by_head_ethnicity_2024', 'gap_history_B', 'first_stage_fit', 'validation_insample', 'selfid_by_region']:
    p = os.path.join(OV, 'tables', t + '.tex')
    if not os.path.exists(p):
        open(p, 'w').write('\\begin{tabular}{l}\\toprule pending \\\\ \\bottomrule\\end{tabular}\n')
if os.environ.get('COMPILE', '1') == '1':
    for cmd in (['pdflatex', '-interaction=nonstopmode', 'main.tex'], ['bibtex', 'main'], ['pdflatex', '-interaction=nonstopmode', 'main.tex'], ['pdflatex', '-interaction=nonstopmode', 'main.tex']):
        r = subprocess.run(cmd, cwd=OV, capture_output=True, text=True)
    log = open(os.path.join(OV, 'main.log'), errors='ignore').read()
    errs = [l for l in log.splitlines() if l.startswith('!') or 'Undefined control sequence' in l]
    print('compile errors:', errs[:10] if errs else 'none')
    print('pdf:', os.path.exists(os.path.join(OV, 'main.pdf')))
